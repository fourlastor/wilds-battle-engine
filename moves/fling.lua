-- Move 374. PokeAPI identity; Gen 8 behavior (see catalog.json).
return {
  id = "fling", name = "Fling", type = Type.Dark,
  category = Category.Physical, pp = 10, accuracy = 1.0,
  priority = 0, target = Target.AnyOther,
  flags = {"no_parental_bond"},
  script = function(ctx)
    local item = ctx.user.item
    local power = powers[(item or ""):gsub("[^%w]", ""):lower()]
    if not power or not ctx.user.item_active or not ctx:item_removable(ctx.user) then ctx:fail(); return end
    ctx:consume_item(ctx.user, false)
    local hit = ctx:damage(power)
    if hit.hit and not hit.substitute then ctx:receive_berry(ctx.target, item) end
  end,
}
