  category = Category.Status, pp = 10, accuracy = Accuracy.Always,
  priority = 0, target = Target.User,
  flags = {"calls_move"},
  script = function(ctx)
    local choices = {}
    for _, id in ipairs(ctx:move_ids()) do
      local number = eligible[id:gsub("[^%w]", ""):lower()]
      if number then choices[#choices+1]={id=id, number=number} end
    end
    table.sort(choices, function(a,b) return a.number < b.number end)
    if #choices == 0 then ctx:fail(); return end
    ctx:call_move(choices[ctx:random_int(1, #choices)].id)
  end,
