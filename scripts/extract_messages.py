#!/usr/bin/env python3
"""Writes locale/battle.pot: every battle message key in the engine and its move scripts.

Keys are English templates whose {0}, {1}... placeholders are the message arguments
(see "Battle messages" in the README). Run with --check to fail when the file is stale.
"""

import argparse
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "locale" / "battle.pot"
STRING = r'"((?:[^"\\]|\\.)*)"'

RUST_PATTERNS = [
    re.compile(r"\bsay\(\s*" + STRING),
    re.compile(r"\bMessage::new\(\s*" + STRING),
    re.compile(r"BattleEvent::Message\(\s*" + STRING + r"\s*\.into\(\)"),
    # Keys chosen before being passed on, marked with the no-op `msg` function.
    re.compile(r"\bmsg\(\s*" + STRING + r"\s*\)"),
]
LUA_PATTERNS = [
    re.compile(r"ctx:message\(\s*" + STRING),
    re.compile(r"\b\w*message\s*=\s*" + STRING),
    re.compile(r"\btwo_turns\([^,]*,\s*" + STRING),
]


def unescape(text: str) -> str:
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text)


def without_tests(source: str) -> str:
    """Drops a trailing `#[cfg(test)]` module, whose messages are not shown to players."""
    index = source.find("#[cfg(test)]\nmod tests")
    return source if index < 0 else source[:index]


def collect() -> dict[str, set[str]]:
    keys: dict[str, set[str]] = defaultdict(set)
    sources = [
        (path, RUST_PATTERNS, without_tests)
        for path in sorted((ROOT / "crates" / "wilds-battle-engine" / "src").glob("*.rs"))
    ] + [
        (path, LUA_PATTERNS, lambda text: text)
        for path in sorted((ROOT / "crates" / "wilds-battle-engine" / "src").glob("*.lua"))
        + sorted((ROOT / "moves").glob("*.lua"))
    ]
    for path, patterns, prepare in sources:
        text = prepare(path.read_text(encoding="utf-8"))
        for pattern in patterns:
            for match in pattern.finditer(text):
                key = unescape(match.group(1))
                if key:
                    keys[key].add(path.relative_to(ROOT).as_posix())
    return keys


def po_string(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def render(keys: dict[str, set[str]]) -> str:
    lines = [
        "# Battle messages of wilds-battle-engine, generated by scripts/extract_messages.py.",
        "# {0}, {1}... are the message arguments: Pokémon, moves, translatable text or numbers.",
        "# Messages about a Pokémon carry its gender as context (Male, Female, Genderless),",
        "# so a translation can add gendered variants with msgctxt.",
        'msgid ""',
        'msgstr ""',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        "",
    ]
    for key in sorted(keys):
        lines.append("#: " + " ".join(sorted(keys[key])))
        lines.append("msgid " + po_string(key))
        lines.append('msgstr ""')
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if locale/battle.pot is stale")
    args = parser.parse_args()
    text = render(collect())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("locale/battle.pot is stale: run scripts/extract_messages.py")
        return
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"{len(collect())} messages written to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
